use x86_64::instructions::port::Port;

/// Перезагружает компьютер.
///
/// Контроллер клавиатуры 8042 исторически управляет линией сброса процессора:
/// команда 0xFE в порт 0x64 даёт импульс на неё
pub fn reboot() -> ! {
    super::without_interrupts(|| unsafe {
        Port::<u8>::new(0x64).write(0xfe);
    });
    super::hlt_loop();
}

/// Выключает компьютер.
///
/// По-честному это делается через ACPI: нужно найти в памяти его таблицы и
/// узнать из них порт и значение. Мы этого пока не умеем, поэтому используем
/// порт, по которому выключается QEMU (`-machine pc`, начиная с версии 2.0).
/// На другом «железе» запись в этот порт ничего не сделает
pub fn poweroff() -> ! {
    super::without_interrupts(|| unsafe {
        Port::<u16>::new(0x604).write(0x2000);
    });
    super::hlt_loop();
}
